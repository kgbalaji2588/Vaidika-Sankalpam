/**
 * Helper to render the Sankalpam template with dynamic Panchanga values.
 * Respects strict requirements (Rule 11, Rule 16):
 * - Never rewrites or alters punctuation.
 * - Same TITHI value is rendered twice identically.
 */
export function renderSankalpam(template: SankalpamSection[], variables: Panchanga): SankalpamSection[] {
  return template.map(section => {
    if (section.isFixed) {
      return { ...section };
    }

    let renderedContent = section.content;

    // Direct substitutions for exact keys
    renderedContent = renderedContent.replace(/\{\{SAMVATSARA\}\}/g, variables.samvatsara);
    renderedContent = renderedContent.replace(/\{\{AYANA\}\}/g, variables.ayana);
    renderedContent = renderedContent.replace(/\{\{RITU\}\}/g, variables.ritu);
    renderedContent = renderedContent.replace(/\{\{MASA\}\}/g, variables.masa);
    renderedContent = renderedContent.replace(/\{\{PAKSHA\}\}/g, variables.paksha);
    renderedContent = renderedContent.replace(/\{\{TITHI\}\}/g, variables.tithi);
    renderedContent = renderedContent.replace(/\{\{VARA\}\}/g, variables.vara);
    renderedContent = renderedContent.replace(/\{\{NAKSHATRA\}\}/g, variables.nakshatra);
    renderedContent = renderedContent.replace(/\{\{YOGA\}\}/g, variables.yoga);
    renderedContent = renderedContent.replace(/\{\{KARANA\}\}/g, variables.karana);

    return {
      ...section,
      content: renderedContent
    };
  });
}
